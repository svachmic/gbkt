// =============================================================================
// Phase 13.7 Plan 05 (Req 4) — Palette polarity WARNING emission tests.
//
// These tests verify the non-fatal WARNING logic wired into BOTH convert tasks:
//
//   BG path (ConvertZoneTilesetsTask):
//     - parsePaletteRgb555Values + checkPalettePolarity → warn if inverted
//   OBJ path (ConvertSpritesTask):
//     - parsePaletteRgb555Values + checkPalettePolarity → warn if inverted
//
// Tests:
//   Test 1: parsePaletteRgb555Values parses C file correctly
//   Test 2: parsePaletteRgb555Values parses C file correctly
//   Test 3: BG WARNING condition — inverted C output triggers checkPalettePolarity=true
//   Test 4: BG WARNING condition — corrected C output triggers checkPalettePolarity=false
//   Test 5: OBJ WARNING condition — inverted C output triggers checkPalettePolarity=true
//   Test 6: OBJ WARNING condition — corrected C output triggers checkPalettePolarity=false
//   Test 7: ConvertZoneTilesetsTask completes without throw on inverted fixture (skip-guarded)
//   Test 8: ConvertSpritesTask completes without throw on inverted fixture (skip-guarded)
//
// The "exactly one warn per inverted asset" and "zero warns on corrected" contracts are
// proven through Tests 3-6 which test the same conditional logic that drives the
// logger.warn call in each task. A checkPalettePolarity return of true = one warn would
// be emitted; false = zero warns would be emitted.
//
// Tests 7-8 prove the non-fatal contract: the task does not throw on an inverted palette
// (build EXIT 0 equivalent). Both tests are skip-guarded for png2asset.
// =============================================================================

class PalettePolarityWarningTest {

    @TempDir lateinit var tempDir: File

    // -------------------------------------------------------------------------
    // Test 1: parsePaletteRgb555Values correctly parses a C palette array in RGB8() form
    //         (the real png2asset output format for indexed BG tilesets)
    // -------------------------------------------------------------------------

    @Test
    fun `parsePaletteRgb555Values parses RGB8 macro palette_color_t array from C file`() {
        val cFile = File(tempDir, "test_tileset.c")
        // Write a synthetic C file with RGB8(r,g,b) format — the actual png2asset output shape.
        // Ascending luminance: black < dark < light < white
        cFile.writeText(
            """
            /* Generated by png2asset */
            const palette_color_t _zone_test_tileset_palettes[4] = {
            	RGB8(  0,  0,  0), RGB8( 64, 64, 64), RGB8(192,192,192), RGB8(255,255,255)
            	};
            """
                .trimIndent()
        )

        val symbol = "_zone_test_tileset_palettes"
        val values = parsePaletteRgb555Values(cFile, symbol)
        assertNotNull(
            values,
            "parsePaletteRgb555Values must parse an RGB8-format palette_color_t array",
        )
        assertTrue(values!!.isNotEmpty(), "Parsed values must not be empty")
        assertTrue(
            values.size == 4,
            "Must parse 4 palette entries from RGB8 form; got ${values.size}: $values",
        )
        // Black (0,0,0) → RGB555 = 0
        assertTrue(values[0] == 0, "First entry RGB8(0,0,0) must map to RGB555=0; got ${values[0]}")
        // White (255,255,255) → RGB555 = 0x7FFF = 32767
        assertTrue(
            values[3] == 0x7FFF,
            "Last entry RGB8(255,255,255) must map to RGB555=0x7FFF; got ${values[3]}",
        )
    }

