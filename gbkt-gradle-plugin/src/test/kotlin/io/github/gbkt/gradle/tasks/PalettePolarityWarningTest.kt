    // -------------------------------------------------------------------------
    // Test 3: BG WARNING condition — inverted emitted palette triggers polarity check
    //
    // Source PNG: ascending luminance PLTE (black → dark → light → white)
    // Emitted C: RGB8 values in DESCENDING luminance order (white → light → dark → black)
    // Expected: checkPalettePolarity returns true → exactly one warn would be emitted
    // -------------------------------------------------------------------------

    @Test
    fun `BG polarity check triggers for inverted emitted palette (exactly one warn condition)`() {
        // Source PNG with ascending-luminance PLTE: black < dark-gray < light-gray < white
        val sourcePng = writeAscendingLumIndexedPng("world1-tileset.png")

        // Emitted C with DESCENDING luminance order (inverted relative to PLTE)
        // Uses RGB8(r,g,b) format — the actual png2asset output format.
        val outputC = File(tempDir, "_zone_test_tileset.c")
        val invertedSymbol = "_zone_test_tileset_palettes"
        outputC.writeText(
            """
            const palette_color_t ${invertedSymbol}[4] = {
            	RGB8(255,255,255), RGB8(192,192,192), RGB8( 64, 64, 64), RGB8(  0,  0,  0)
            	};
            """
                .trimIndent()
        )

        // Simulate the BG WARNING logic: parse → checkPalettePolarity
        val values = parsePaletteRgb555Values(outputC, invertedSymbol)
        assertNotNull(values, "parsePaletteRgb555Values must parse the inverted RGB8 palette array")
        val polarity = checkPalettePolarity(sourcePng, values!!)
        assertTrue(
            polarity,
            "BG inverted fixture: checkPalettePolarity must return true → one warn would be emitted. " +
                "values=$values",
        )
    }

