    // -------------------------------------------------------------------------
    // Test 7: ConvertZoneTilesetsTask does NOT throw on an inverted palette PNG
    //         (non-fatal contract; build EXIT 0 equivalent)
    //
    // Skip-guarded: returns if png2asset is not available.
    // Uses a real indexed PNG fixture with descending luminance PLTE.
    // Asserts: convertZoneTilesets() completes without throwing.
    // -------------------------------------------------------------------------

    @Test
    fun `ConvertZoneTilesetsTask does not throw when BG palette is inverted (non-fatal)`() {
        val gbdkDir =
            try {
                GbdkToolchain.find(null)
            } catch (_: Exception) {
                return
            }
        val png2asset = GbdkToolchain.getPng2asset(gbdkDir)
        if (!png2asset.exists()) return

        // Use the real world1-tileset.png as the fixture (if available in this checkout).
        // It is a real indexed PNG — the polarity check will run against it.
        val realPng = findPlatformerTemplatePng("world1-tileset.png") ?: return

        val assetDir = File(tempDir, "res").apply { mkdirs() }
        val gfxDir = File(assetDir, "graphics").apply { mkdirs() }
        realPng.copyTo(File(gfxDir, "world1-tileset.png"), overwrite = true)

        val metadataFile = File(tempDir, "game_metadata.json")
        metadataFile.writeText(
            """
            {
              "zoneTilesets": [
                {
                  "id": "world1Area1Zone",
                  "path": "graphics/world1-tileset.png",
                  "sanitizedSymbol": "world1Area1Zone",
                  "mapWidth": 60,
                  "mapHeight": 32,
                  "bank": 2
                }
              ]
            }
            """
                .trimIndent()
        )

        val cSourceDir = File(tempDir, "out").apply { mkdirs() }
        val project = ProjectBuilder.builder().withProjectDir(tempDir).build()
        val task =
            project.tasks
                .register("convertZoneTilesetsPolarity", ConvertZoneTilesetsTask::class.java) {
                    gbdkHome.set(gbdkDir.absolutePath)
                    assetDirectory.set(assetDir)
                    this.metadataFile.set(metadataFile)
                    this.cSourceDir.set(cSourceDir)
                }
                .get()

        // Must NOT throw — the polarity WARNING is non-fatal (warn-not-fail).
        // Any GradleException or other exception would indicate a regression.
        var threw: Throwable? = null
        try {
            task.convertZoneTilesets()
        } catch (e: Throwable) {
            threw = e
        }

        assertTrue(
            threw == null,
            "ConvertZoneTilesetsTask must not throw for an inverted palette PNG " +
                "(non-fatal WARNING contract). Exception: $threw",
        )

        // Secondary: output .c was produced (task ran to completion)
        val outC = File(cSourceDir, "_zone_world1Area1Zone_tileset.c")
        assertTrue(
            outC.exists(),
            "Output .c must exist — task must run to completion even if palette is inverted. " +
                "path: ${outC.absolutePath}",
        )
    }

