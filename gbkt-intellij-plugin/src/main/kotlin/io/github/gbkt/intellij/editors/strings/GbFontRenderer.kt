    /** Default character for unknown characters. */
    private val unknownChar = byteArrayOf(0x7E, 0x42, 0x42, 0x42, 0x42, 0x42, 0x7E, 0x00)

    /**
     * Renders text to an image using the GB font.
     *
     * @param text The text to render
     * @param scale Scale factor (1 = actual GB size)
     * @param palette The color palette to use (4 colors, index 0 = background, 3 = text)
     * @return BufferedImage with the rendered text
     */
    fun renderText(
        text: String,
        scale: Int = 2,
        palette: List<Color> = GbColors.DMG_PALETTE,
    ): BufferedImage {
        val lines = text.split("\n")
        val maxWidth = lines.maxOfOrNull { it.length } ?: 1
        val width = maxWidth * CHAR_WIDTH * scale
        val height = lines.size * CHAR_HEIGHT * scale

        val image =
            BufferedImage(
                width.coerceAtLeast(1),
                height.coerceAtLeast(1),
                BufferedImage.TYPE_INT_ARGB,
            )
        val g = image.createGraphics()

        // Fill background
        g.color = palette[0]
        g.fillRect(0, 0, width, height)

        // Render each character
        g.color = palette[3]
        renderLines(g, lines, 0, 0, scale)

        g.dispose()
        return image
    }

    private fun renderLines(g: Graphics2D, lines: List<String>, x: Int, y: Int, scale: Int) {
        for ((lineIndex, line) in lines.withIndex()) {
            renderLine(g, line, x, y + lineIndex * CHAR_HEIGHT * scale, scale)
        }
    }

    private fun renderLine(g: Graphics2D, line: String, x: Int, y: Int, scale: Int) {
        for ((charIndex, char) in line.withIndex()) {
            renderCharacter(g, char, x + charIndex * CHAR_WIDTH * scale, y, scale)
        }
    }

    private fun renderCharacter(g: Graphics2D, char: Char, x: Int, y: Int, scale: Int) {
        val charData = fontData[char] ?: unknownChar
        for (row in 0 until CHAR_HEIGHT) {
            val rowData = charData[row].toInt() and 0xFF
            for (col in 0 until CHAR_WIDTH) {
                if ((rowData and (0x80 shr col)) != 0) {
                    g.fillRect(x + col * scale, y + row * scale, scale, scale)
                }
            }
        }
    }

    /**
     * Renders text directly to a Graphics2D context.
     *
     * @param g2 The graphics context
     * @param text The text to render
     * @param x Starting X position
     * @param y Starting Y position
     * @param scale Scale factor
     * @param textColor Color for the text
     */
    fun renderText(
        g2: Graphics2D,
        text: String,
        x: Int,
        y: Int,
        scale: Int = 2,
        textColor: Color = Color.BLACK,
    ) {
        g2.color = textColor
        val lines = text.split("\n")
        renderLines(g2, lines, x, y, scale)
    }

    /** Returns the width in pixels of the given text at the specified scale. */
    fun getTextWidth(text: String, scale: Int = 1): Int {
        val lines = text.split("\n")
        val maxWidth = lines.maxOfOrNull { it.length } ?: 0
        return maxWidth * CHAR_WIDTH * scale
    }

    /** Returns the height in pixels of the given text at the specified scale. */
    fun getTextHeight(text: String, scale: Int = 1): Int {
        val lines = text.split("\n")
        return lines.size * CHAR_HEIGHT * scale
    }
